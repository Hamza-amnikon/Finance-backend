using System.ComponentModel.DataAnnotations;

namespace SalesInvoiceService.API.Models
{
    public enum SalesInvoiceStatus
    {
        Draft = 0,
        Issued = 1,
        Void = 2
    }

    public class SalesInvoice
    {
        [Key]
        public int Id { get; set; }

        public Guid ClientId { get; set; }

        public int? SourceEstimateId { get; set; }

        [MaxLength(50)]
        public string? SourceEstimateNumber { get; set; }

        [MaxLength(8)]
        public byte[]? SourceEstimateRowVersion { get; set; }

        public DateOnly? SourceEstimateInvoiceDate { get; set; }

        public DateOnly? SourceEstimateDueDate { get; set; }

        // Generated by the backend when the invoice is issued.
        [MaxLength(50)]
        public string? InvoiceNumber { get; set; }

        // Client details copied onto the invoice.
        [Required]
        [MaxLength(200)]
        public string ClientName { get; set; } = string.Empty;

        [MaxLength(200)]
        public string CompanyName { get; set; } = string.Empty;

        [MaxLength(1000)]
        public string BillingAddress { get; set; } = string.Empty;

        public DateOnly InvoiceDate { get; set; }

        public DateOnly DueDate { get; set; }

        // Optional period covered by the services.
        public DateOnly? ServicePeriodStart { get; set; }

        public DateOnly? ServicePeriodEnd { get; set; }

        [Required]
        [MaxLength(3)]
        public string Currency { get; set; } = string.Empty;

        [Required]
        [MaxLength(20)]
        public string Branch { get; set; } = string.Empty;

        [MaxLength(200)]
        public string PaymentTerms { get; set; } = string.Empty;

        [MaxLength(50)]
        public string PreferredPaymentMode { get; set; } = string.Empty;

        // Client PO, contract, or project reference.
        [MaxLength(200)]
        public string Reference { get; set; } = string.Empty;

        // Calculated by the backend from invoice items.
        public decimal SubTotal { get; set; }

        public decimal DiscountTotal { get; set; }

        public decimal TaxTotal { get; set; }

        public decimal GrandTotal { get; set; }

        public SalesInvoiceStatus Status { get; set; } =
            SalesInvoiceStatus.Draft;

        [MaxLength(2000)]
        public string Notes { get; set; } = string.Empty;

        [MaxLength(2000)]
        public string AdditionalTerms { get; set; } = string.Empty;

        public DateTime CreatedDate { get; set; } =
            DateTime.UtcNow;

        public DateTime? ModifiedDate { get; set; }

        public DateTime? IssuedDate { get; set; }

        // Frozen when issued; later branch edits do not change this invoice.
        public string IssuerSnapshotJson { get; set; } = string.Empty;

        [MaxLength(30)]
        public string InvoiceTemplateVersion { get; set; } = string.Empty;

        public DateTime? VoidedDate { get; set; }

        [MaxLength(1000)]
        public string VoidReason { get; set; } = string.Empty;

        [Timestamp]
        public byte[] RowVersion { get; set; } = [];

        public ICollection<SalesInvoiceItem> Items { get; set; } =
            new List<SalesInvoiceItem>();
    }
}